import AppKit
import Combine
import CryptoKit
import ImageIO

enum ClipKind: String, Codable { case text, link, code, image }

struct Clip: Codable, Identifiable, Equatable {
    var id = UUID()
    var fingerprint: String
    var kind: ClipKind
    var text: String?
    var imageFile: String?
    var width: Int?
    var height: Int?
    var source: String
    var date = Date()
    var pinned = false

    var title: String {
        if kind == .image { return "图片 · \(width ?? 0) × \(height ?? 0)" }
        return text?.split(whereSeparator: \.isNewline).first.map(String.init) ?? "文字"
    }
    var label: String {
        switch kind { case .text: return "文字"; case .link: return "链接"; case .code: return "代码"; case .image: return "图片" }
    }
    var symbol: String {
        switch kind { case .text: return "text.alignleft"; case .link: return "link"; case .code: return "chevron.left.forwardslash.chevron.right"; case .image: return "photo" }
    }
}

struct ClipSettings: Codable {
    var limit = 200
    var retentionDays = 30
    var captureImages = true
}

final class HistoryStore: ObservableObject {
    @Published private(set) var clips: [Clip] = []
    @Published var paused = false
    @Published var notice: String?
    @Published private(set) var settings = ClipSettings()
    let directory: URL
    let pasteboard: NSPasteboard
    private var lastChange: Int
    private var timer: Timer?
    private let cache = NSCache<NSString, NSImage>()
    private var canSave = true

    init(directory: URL? = nil, pasteboard: NSPasteboard = .general, startMonitoring: Bool = true) {
        self.directory = directory ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("ClipShelf", isDirectory: true)
        self.pasteboard = pasteboard
        self.lastChange = pasteboard.changeCount
        cache.countLimit = 60
        do {
            try FileManager.default.createDirectory(at: imagesDirectory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: self.directory.path)
            if FileManager.default.fileExists(atPath: historyURL.path) {
                clips = try JSONDecoder().decode([Clip].self, from: Data(contentsOf: historyURL))
            }
            if FileManager.default.fileExists(atPath: settingsURL.path) {
                settings = (try? JSONDecoder().decode(ClipSettings.self, from: Data(contentsOf: settingsURL))) ?? ClipSettings()
            }
            prune()
        } catch {
            canSave = false
            notice = "历史记录未能读取，已停止保存。请检查存储文件夹。"
        }
        if startMonitoring { start() }
    }

    deinit { timer?.invalidate() }
    private var historyURL: URL { directory.appendingPathComponent("history.json") }
    private var settingsURL: URL { directory.appendingPathComponent("settings.json") }
    private var imagesDirectory: URL { directory.appendingPathComponent("Images", isDirectory: true) }

    func start() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            self?.poll()
        }
        if let timer { RunLoop.main.add(timer, forMode: .common) }
    }

    static func isSensitive(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        let markers = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        return types.contains { markers.contains($0.rawValue) || $0.rawValue.lowercased().contains("concealed") }
    }

    func poll(sourceOverride: String? = nil) {
        guard lastChange != pasteboard.changeCount else { return }
        lastChange = pasteboard.changeCount
        guard !paused, canSave else { return }
        guard !Self.isSensitive(pasteboard.types ?? []) else { return }
        let front = NSWorkspace.shared.frontmostApplication
        let excluded = ["com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop", "com.apple.keychainaccess"]
        guard sourceOverride != nil || !excluded.contains(front?.bundleIdentifier?.lowercased() ?? "") else { return }
        let source = sourceOverride ?? front?.localizedName ?? "剪贴板"

        // Text first preserves a copied URL even when a browser also supplies an image.
        if let value = pasteboard.string(forType: .string), !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard value.utf8.count <= 512_000 else { notice = "这段文字超过 500 KB，已跳过记录。"; return }
            addText(value, source: source)
        } else if settings.captureImages {
            let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff)
            if let data, data.count <= 16_000_000 { addImage(data, source: source) }
        }
    }

    func addText(_ text: String, source: String, date: Date = Date()) {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        var kind = ClipKind.text
        if let url = URL(string: trimmed), ["http", "https", "mailto"].contains(url.scheme?.lowercased() ?? ""), !trimmed.contains(where: \.isWhitespace) {
            kind = .link
        } else if text.contains("\n") && ["func ", "function ", "const ", "import ", "def ", "class ", "=>", "</"].contains(where: text.contains) {
            kind = .code
        }
        upsert(Clip(fingerprint: digest(Data(text.utf8)), kind: kind, text: text, source: source, date: date))
    }

    func addImage(_ data: Data, source: String) {
        guard let rep = NSBitmapImageRep(data: data), rep.pixelsWide <= 12_000, rep.pixelsHigh <= 12_000,
              let png = rep.representation(using: .png, properties: [:]), png.count <= 16_000_000 else { return }
        let fingerprint = digest(png)
        let name = fingerprint + ".png"
        do {
            let url = imagesDirectory.appendingPathComponent(name)
            if !FileManager.default.fileExists(atPath: url.path) {
                try png.write(to: url, options: .atomic)
                try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            }
            upsert(Clip(fingerprint: fingerprint, kind: .image, imageFile: name, width: rep.pixelsWide, height: rep.pixelsHigh, source: source))
        } catch { notice = "图片保存失败，请检查可用磁盘空间。" }
    }

    private func digest(_ data: Data) -> String { SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() }

    private func upsert(_ incoming: Clip) {
        var clip = incoming
        if let index = clips.firstIndex(where: { $0.fingerprint == clip.fingerprint && $0.kind == clip.kind }) {
            let previous = clips.remove(at: index)
            clip.id = previous.id
            clip.pinned = previous.pinned
        }
        clips.insert(clip, at: 0)
        prune()
        save()
    }

    func togglePin(_ clip: Clip) {
        guard let index = clips.firstIndex(where: { $0.id == clip.id }) else { return }
        clips[index].pinned.toggle()
        prune()
        save()
    }

    func remove(_ clip: Clip) {
        clips.removeAll { $0.id == clip.id }
        deleteImage(clip)
        save()
    }

    func clearUnpinned() {
        let removed = clips.filter { !$0.pinned }
        clips.removeAll { !$0.pinned }
        removed.forEach(deleteImage)
        save()
    }

    func updateSettings(limit: Int? = nil, retentionDays: Int? = nil, captureImages: Bool? = nil) {
        if let limit { settings.limit = max(50, min(1000, limit)) }
        if let retentionDays { settings.retentionDays = max(0, retentionDays) }
        if let captureImages { settings.captureImages = captureImages }
        prune()
        save()
        do { try JSONEncoder().encode(settings).write(to: settingsURL, options: .atomic) }
        catch { notice = "设置保存失败。" }
    }

    func prune(now: Date = Date()) {
        var count = 0
        var removed: [Clip] = []
        let cutoff = now.addingTimeInterval(-Double(settings.retentionDays) * 86400)
        clips = clips.filter { clip in
            if clip.pinned { return true }
            count += 1
            let keep = count <= settings.limit && (settings.retentionDays == 0 || clip.date >= cutoff)
            if !keep { removed.append(clip) }
            return keep
        }
        removed.forEach(deleteImage)
    }

    private func deleteImage(_ clip: Clip) {
        guard let name = clip.imageFile, name == URL(fileURLWithPath: name).lastPathComponent else { return }
        cache.removeObject(forKey: name as NSString)
        try? FileManager.default.removeItem(at: imagesDirectory.appendingPathComponent(name))
    }

    func imageURL(for clip: Clip) -> URL? {
        guard let name = clip.imageFile, name == URL(fileURLWithPath: name).lastPathComponent else { return nil }
        return imagesDirectory.appendingPathComponent(name)
    }

    func image(for clip: Clip, thumbnail: Bool = true) -> NSImage? {
        guard let url = imageURL(for: clip) else { return nil }
        if !thumbnail { return NSImage(contentsOf: url) }
        let key = url.lastPathComponent as NSString
        if let cached = cache.object(forKey: key) { return cached }
        let options: [CFString: Any] = [kCGImageSourceCreateThumbnailFromImageAlways: true,
                                      kCGImageSourceThumbnailMaxPixelSize: 96,
                                      kCGImageSourceCreateThumbnailWithTransform: true]
        guard let source = CGImageSourceCreateWithURL(url as CFURL, nil),
              let cgImage = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        let image = NSImage(cgImage: cgImage, size: NSSize(width: cgImage.width, height: cgImage.height))
        cache.setObject(image, forKey: key)
        return image
    }

    @discardableResult func copy(_ clip: Clip) -> Bool {
        let item = NSPasteboardItem()
        if let text = clip.text {
            item.setString(text, forType: .string)
        } else if let url = imageURL(for: clip), let data = try? Data(contentsOf: url) {
            item.setData(data, forType: .png)
        } else { notice = "这条记录的内容无法读取。"; return false }
        pasteboard.clearContents()
        let success = pasteboard.writeObjects([item])
        lastChange = pasteboard.changeCount
        if !success { notice = "复制失败，请再试一次。" }
        return success
    }

    func save() {
        guard canSave else { return }
        do {
            try JSONEncoder().encode(clips).write(to: historyURL, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: historyURL.path)
        } catch { notice = "历史保存失败，请检查可用磁盘空间。" }
    }

    func matching(query: String, filter: Int) -> [Clip] {
        let terms = query.split(whereSeparator: \.isWhitespace).map(String.init)
        return clips.filter { clip in
            if filter == 1 && !clip.pinned { return false }
            if filter == 2 && clip.kind != .image { return false }
            let searchable = (clip.text ?? "图片") + " " + clip.source + " " + clip.label
            return terms.allSatisfy { searchable.localizedStandardContains($0) }
        }
    }
}
